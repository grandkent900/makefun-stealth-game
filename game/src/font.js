export const GLYPH_W = 5;
export const GLYPH_H = 7;

// Draw one glyph with a pen that offers fillRect(x, y, w, h).
// scale is the pixel size of one bitmap cell.
export function drawGlyph(pen, ch, x, y, scale) {
  const glyph = GLYPHS[ch] || GLYPHS['?'];
  for (let row = 0; row < GLYPH_H; row++) {
    const line = glyph[row];
    for (let col = 0; col < GLYPH_W; col++) {
      if (line[col] === '#') {
        pen.fillRect(x + col * scale, y + row * scale, scale, scale);
      }
    }
  }
}

// Draw a line of text left-aligned at (x, y). Returns the drawn width.
export function drawText(pen, text, x, y, scale) {
  const upper = String(text).toUpperCase();
  let cursor = x;
  for (const ch of upper) {
    drawGlyph(pen, ch, cursor, y, scale);
    cursor += (GLYPH_W + 1) * scale;
  }
  return cursor - x;
}

export function textWidth(text, scale) {
  return String(text).length * (GLYPH_W + 1) * scale - scale;
}

// Draw text centred on cx at height y.
export function drawTextCentered(pen, text, cx, y, scale) {
  const w = textWidth(text, scale);
  return drawText(pen, text, cx - w / 2, y, scale);
}
